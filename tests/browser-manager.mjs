// Operational Home and share-preview checks with real SQLite. No external messages.
import assert from 'node:assert/strict';
import {chromium, expect} from '@playwright/test';
import {createServer} from 'vite';
import react from '@vitejs/plugin-react';
import {mkdtempSync, existsSync, rmSync, mkdirSync} from 'node:fs';
import {join, resolve, dirname} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {once} from 'node:events';
import {createApp} from '../server/app.js';
import {createStore} from '../server/store.js';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = mkdtempSync(join(tmpdir(), 'potshaven-day-'));
const store = createStore(join(dataDir, 'test.db'), {seed: false});
const date = new Date().toISOString().slice(0, 10);
const prior = new Date(`${date}T12:00:00Z`); prior.setUTCDate(prior.getUTCDate() - 1);
const yesterday = prior.toISOString().slice(0, 10);
store.put('places', {id: 'hotel', name: 'Palm Court', address: 'Accra'});
store.put('workers', {id: 'ama', name: 'Ama', available: true, workforceType: 'External', engagementType: 'Daily', engagementStart: date, engagementEnd: date, agreedRate: 700});
store.put('vehicles', {id: 'van', name: 'Crew van', status: 'Servicing'});
store.put('jobs', {id: 'today', title: 'Entrance care', date, time: '08:00', type: 'Maintenance', status: 'Scheduled', placeId: 'hotel', crewIds: ['ama'], vehicleId: 'van', tasks: [{text: 'Water pots', done: false}, {text: 'Prune', done: true}]});
store.put('jobs', {id: 'late', title: 'Median care', date: yesterday, type: 'Maintenance', status: 'In progress', crewIds: [], tasks: []});
store.put('jobs', {id: 'check', title: 'Courtyard follow-up', date: yesterday, type: 'Maintenance', status: 'Completed', crewIds: [], tasks: [{text: 'Final photo', done: false}]});
store.put('inventory', {id: 'plant', name: 'Peace lily', quantity: 2, minStock: 4, category: 'Plants'});
store.put('payments', {id: 'payment', description: 'Private invoice', amount: 9999, dueDate: yesterday, status: 'Overdue'});
const before = store.state();
const app = createApp({store, dataDir, ownerPassword: '', managerPassword: '', imageKey: ''});
const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
const apiOrigin = `http://127.0.0.1:${server.address().port}`;
const vite = await createServer({configFile: false, root, plugins: [react()], logLevel: 'error', server: {host: '127.0.0.1', port: 0, proxy: {'/api': {target: apiOrigin, changeOrigin: false, xfwd: true}, '/media': {target: apiOrigin, changeOrigin: false, xfwd: true}}}});
await vite.listen();
const baseURL = `http://127.0.0.1:${vite.httpServer.address().port}`;
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), headless: true, args: ['--no-sandbox']});
const page = await browser.newPage({viewport: {width: 390, height: 844}});
const errors = []; page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => {Object.defineProperty(navigator, 'clipboard', {configurable: true, value: {writeText: async value => {window.__copiedPlan = value;}}});});
try {
  await page.goto(`${baseURL}/#overview`);
  await expect(page.getByRole('heading', {name: 'Today at a glance', exact: true})).toBeVisible();
  await expect(page.locator('.md-job')).toHaveCount(1);
  await expect(page.locator('.md-job')).toContainText('Ama');
  await expect(page.locator('.md-job')).toContainText('Crew van');
  await expect(page.locator('.md-job')).toContainText('1/2 tasks checked');
  await expect(page.getByRole('heading', {name: 'Operational reminders', exact: true})).toBeVisible();
  await expect(page.locator('.home-reminders')).toContainText('work agreement needs review');
  await expect(page.locator('.simple-home')).not.toContainText('Private invoice');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.getByRole('group', {name: 'Job view'}).getByRole('button', {name: /Needs attention/}).click();
  await expect(page.locator('.md-job')).toHaveCount(3);
  await expect(page.locator('.md-job').filter({hasText: 'Courtyard follow-up'})).toContainText('Confirm remaining tasks');
  await page.locator('.md-job').filter({hasText: 'Median care'}).click();
  await expect(page.getByLabel('Job title', {exact: true})).toHaveValue('Median care');
  await page.getByRole('button', {name: 'Close dialog', exact: true}).click();
  console.log('PASS mobile Home uses real job/checklist/crew/vehicle facts and opens the correct job for follow-up');

  await page.getByRole('button', {name: 'Prepare daily brief', exact: true}).first().click();
  const brief = page.getByRole('textbox', {name: 'Daily work brief', exact: true});
  await expect(brief).toBeVisible();
  const text = await brief.inputValue();
  assert.match(text, /PotsHavenGh · Daily work plan/);
  assert.match(text, /Pending: Water pots/);
  assert.match(text, /Done: Prune/);
  assert.match(text, /Median care/);
  assert.ok(!text.includes('Private invoice'));
  assert.ok(!text.includes('700'));
  const share = await page.getByRole('link', {name: 'Open WhatsApp', exact: true}).getAttribute('href');
  assert.equal(new URL(share).searchParams.get('text'), text);
  await page.getByRole('button', {name: 'Copy plan', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Copied', exact: true})).toBeVisible();
  assert.equal(await page.evaluate(() => window.__copiedPlan), text);
  assert.deepEqual(store.state(), before);
  mkdirSync('/tmp/potshaven-checks', {recursive: true});
  await page.screenshot({path: '/tmp/potshaven-checks/manager-daily-brief-mobile.png', fullPage: true});
  await page.getByRole('button', {name: 'Close dialog', exact: true}).click();
  await page.screenshot({path: '/tmp/potshaven-checks/manager-home-mobile.png', fullPage: true});
  assert.deepEqual(errors, []);
  console.log('PASS daily brief can be reviewed and copied, WhatsApp opens only on user action, and no company data is changed');
} finally {await browser.close(); await vite.close(); await new Promise(resolve => server.close(resolve)); store.close(); rmSync(dataDir, {recursive: true, force: true});}
