// Real persistence and mobile checks for external work agreements and assignments.
import {chromium, expect} from '@playwright/test';
import {createServer} from 'vite';
import react from '@vitejs/plugin-react';
import {mkdtempSync, existsSync, rmSync} from 'node:fs';
import {join, resolve, dirname} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {once} from 'node:events';
import assert from 'node:assert/strict';
import {createApp} from '../server/app.js';
import {createStore} from '../server/store.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)),'..');
const dataDir = mkdtempSync(join(tmpdir(),'potshaven-workforce-'));
const store = createStore(join(dataDir,'test.db'),{seed:false});
const date = new Date().toISOString().slice(0,10);
store.put('places',{id:'place',name:'Hotel garden',address:'Accra'});
store.put('vehicles',{id:'van',name:'Crew van',registration:'GR 001',status:'Servicing'});
store.put('jobs',{id:'project',title:'Hotel installation',type:'Project',status:'In progress',date,crewIds:[],tasks:[]});
const app = createApp({store,dataDir,ownerPassword:'',managerPassword:'',imageKey:''});
const server = app.listen(0,'127.0.0.1'); await once(server,'listening');
const apiOrigin = `http://127.0.0.1:${server.address().port}`;
const vite = await createServer({configFile:false,root,plugins:[react()],logLevel:'error',server:{host:'127.0.0.1',port:0,proxy:{'/api':{target:apiOrigin,changeOrigin:false,xfwd:true},'/media':{target:apiOrigin,changeOrigin:false,xfwd:true}}}});
await vite.listen();
const baseURL = `http://127.0.0.1:${vite.httpServer.address().port}`;
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined),headless:true,args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:390,height:844}});
const errors = []; page.on('pageerror',error => errors.push(error.message));
try {
  await page.goto(`${baseURL}/#team`);
  await expect(page.getByRole('heading',{name:'Team & vehicles',exact:true})).toBeVisible({timeout:120000});
  await page.getByRole('button',{name:'Add crew member',exact:true}).click();
  await page.getByLabel('Full name',{exact:true}).fill('Ama Contract');
  await page.getByLabel('Worker group',{exact:true}).selectOption('External');
  await page.getByLabel('Work agreement',{exact:true}).selectOption('Until job complete');
  await page.getByLabel('Work until this job is complete',{exact:true}).selectOption('project');
  await page.getByText('Pay & agreement details',{exact:true}).click();
  await page.getByLabel('Agreed rate (GHS)',{exact:true}).fill('900');
  await page.getByLabel('Agreement status',{exact:true}).selectOption('Signed');
  await page.getByLabel('Signed agreement reference',{exact:true}).fill('Signed hotel scope');
  await page.getByLabel('Agreed work & crew instructions',{exact:true}).fill('Install the courtyard pots only.');
  await page.getByRole('button',{name:'Save crew member',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const worker = store.list('workers')[0];
  assert.equal(worker.workforceType,'External');
  assert.equal(worker.engagementType,'Until job complete');
  assert.equal(worker.relatedJobId,'project');
  assert.equal(worker.agreedRate,900);
  assert.equal(worker.agreementStatus,'Signed');
  assert.equal(worker.engagementEnd,'');
  await page.getByLabel('Filter workers',{exact:true}).selectOption('External workers');
  await expect(page.getByRole('heading',{name:'Ama Contract',exact:true})).toBeVisible();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2),false);
  console.log('PASS external completion-based work agreement, pay/reference persistence, and mobile team layout');

  await page.goto(`${baseURL}/#schedule`);
  await page.getByRole('button',{name:'Schedule a visit',exact:true}).click();
  await page.getByLabel('Job title',{exact:true}).fill('Courtyard care');
  await page.getByLabel('Place',{exact:true}).selectOption('place');
  await page.getByLabel('Ama Contract',{exact:true}).check();
  await page.getByLabel('Vehicle',{exact:true}).selectOption('van');
  await expect(page.getByText('Crew van is marked servicing.',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Assignment summary')).toContainText('Ama Contract');
  await expect(page.getByLabel('Assignment summary')).toContainText('Crew van');
  await page.getByRole('button',{name:'Create job',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const scheduled = store.list('jobs').find(job => job.title === 'Courtyard care');
  assert.deepEqual(scheduled.crewIds,[worker.id]);
  assert.equal(scheduled.vehicleId,'van');
  const whatsapp = decodeURIComponent(await page.getByRole('link',{name:'Share route on WhatsApp'}).getAttribute('href'));
  assert.match(whatsapp,/Crew: Ama Contract/);
  assert.match(whatsapp,/Vehicle: Crew van GR 001/);
  assert.match(whatsapp,/agreed work: Install the courtyard pots only/);
  console.log('PASS crew/vehicle assignment, service warning, and contractor scope in WhatsApp draft');

  store.update('jobs','project',{status:'Completed'});
  await page.goto(`${baseURL}/#team`);
  await page.reload();
  await expect(page.getByText('Until job complete · Work complete',{exact:true})).toBeVisible();
  await page.getByLabel('Filter workers',{exact:true}).selectOption('Ready to assign');
  await expect(page.getByRole('heading',{name:'Ama Contract',exact:true})).toHaveCount(0);
  await page.getByLabel('Filter workers',{exact:true}).selectOption('Ended agreements');
  await expect(page.getByRole('heading',{name:'Ama Contract',exact:true})).toBeVisible();
  assert.deepEqual(errors,[]);
  console.log('PASS completed contract job ends agreement availability without deleting worker history');
} finally {
  await browser.close(); await vite.close(); await new Promise(resolve => server.close(resolve));
  store.close(); rmSync(dataDir,{recursive:true,force:true});
}
